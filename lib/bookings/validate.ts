import { STUDIO } from '@/lib/constants';

/**
 * What a service booking must have before money is taken, and what it can
 * simply fill in.
 *
 * Pulled out of the route so it can be tested. It was worth testing: this check
 * refused every studio booking on the platform. `deliverables` was in the
 * required list, and neither route that reaches the endpoint has ever sent it —
 * Ubunye's link template did not carry it and the booking form did not ask for
 * it. So a customer picked a shoot, a date and a duration, saw a correct total,
 * pressed pay, and was told four fields were missing. The message named all
 * four whether or not they were the problem, which pointed anyone debugging it
 * at the wrong three.
 *
 * The rule now: refuse only what a booking cannot exist without, which is what
 * kind of shoot and how long. Everything else is information to gather, and an
 * admin confirms it before the shoot.
 */

export interface BookingRequestInput {
  project_category?: unknown;
  project_description?: unknown;
  deliverables?: unknown;
  duration_hours?: unknown;
  location?: unknown;
  preferred_dates?: unknown;
}

export type BookingValidation =
  | { ok: false; error: string }
  | { ok: true; projectCategory: string; projectDescription: string; deliverables: string; durationHours: number };

const asText = (v: unknown): string => (typeof v === 'string' ? v.trim() : '');

/** Stand-in when nobody has said what they want back. Never left null: the column is NOT NULL. */
export const DELIVERABLES_PLACEHOLDER = 'To be confirmed';

export function validateBookingRequest(input: BookingRequestInput): BookingValidation {
  const projectCategory = asText(input.project_category);
  const durationHours = input.duration_hours;

  const missing: string[] = [];
  if (!projectCategory) missing.push('project_category');
  if (!durationHours) missing.push('duration_hours');

  if (missing.length > 0) {
    return { ok: false, error: `Missing required fields: ${missing.join(', ')}` };
  }

  if (
    typeof durationHours !== 'number'
    || !Number.isFinite(durationHours)
    || durationHours < STUDIO.booking.minBookingHours
    || durationHours > STUDIO.booking.maxBookingHours
  ) {
    return {
      ok: false,
      error: `Duration must be between ${STUDIO.booking.minBookingHours} and ${STUDIO.booking.maxBookingHours} hours`,
    };
  }

  const suppliedDescription = asText(input.project_description);
  const location = asText(input.location);
  const dates = asText(input.preferred_dates);

  // A description the client actually wrote is kept. One generated by the
  // confirmation page is often shorter than the old 20-character floor, and
  // rejecting the customer for a sentence they never typed is not a validation,
  // it is a dead end.
  const projectDescription = suppliedDescription.length >= 20
    ? suppliedDescription
    : `${projectCategory} — ${durationHours} hour${durationHours === 1 ? '' : 's'}`
      + `${dates ? ` on ${dates}` : ''}`
      + `${location ? ` in ${location}` : ''}`
      + '. Details to be confirmed with the client.';

  const deliverables = asText(input.deliverables) || DELIVERABLES_PLACEHOLDER;

  return { ok: true, projectCategory, projectDescription, deliverables, durationHours };
}
